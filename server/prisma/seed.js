// Seeds fictional demo data. Usage: npm run db:seed (from server/) — destroys existing data in the target DB.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PrismaClient } from '@prisma/client';
import { seed, DEMO_PASSWORD } from './seed-lib.js';

if (process.env.NODE_ENV === 'production' && process.env.ALLOW_PRODUCTION_SEED !== 'true') {
  console.error('Refusing to seed in production (it deletes all data). Set ALLOW_PRODUCTION_SEED=true to override.');
  process.exit(1);
}

const prisma = new PrismaClient();
const started = Date.now();
const result = await seed(prisma);
await prisma.$disconnect();

const { edunexus, analytics } = result.clients;
console.log(`\nSeed complete in ${((Date.now() - started) / 1000).toFixed(1)}s.\n`);
console.log('Demo sign-ins (password for all: %s)', DEMO_PASSWORD);
console.log('  Administrator  admin@feddrick.edu');
console.log('  Registrar      registrar@feddrick.edu');
console.log('  Faculty        e.vasquez@feddrick.edu');
console.log('  Student        maya.chen@students.feddrick.edu');
console.log('  Student (hold) jordan.rivera@students.feddrick.edu\n');
console.log('Integration clients (secrets are shown only now — they are stored hashed):');
for (const c of [edunexus, analytics]) console.log(`  ${c.name}\n    client_id:     ${c.clientId}\n    client_secret: ${c.clientSecret}`);

// Local developer convenience: write the EdunexusAI connector's credentials to its git-ignored .env.
const connectorEnv = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../connector/.env');
if (process.env.NODE_ENV !== 'production' && process.env.NODE_ENV !== 'test') {
  fs.writeFileSync(connectorEnv, `# Generated by the CampusCore seed for local development. Do not commit.\nCAMPUSCORE_BASE_URL=http://localhost:4000\nCAMPUSCORE_CLIENT_ID=${edunexus.clientId}\nCAMPUSCORE_CLIENT_SECRET=${edunexus.clientSecret}\nPORT=4100\n`, { mode: 0o600 });
  console.log(`\nWrote EdunexusAI connector credentials to ${path.relative(process.cwd(), connectorEnv)} (git-ignored).`);
}
